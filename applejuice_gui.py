# ── BLE advertising ───────────────────────────────────────────────────────────
def make_publisher(raw):
    from winrt.windows.devices.bluetooth.advertisement import (
        BluetoothLEAdvertisement,
        BluetoothLEAdvertisementPublisher,
        BluetoothLEManufacturerSpecificData,
    )
    from winrt.windows.storage.streams import DataWriter

    company_id = (raw[3] << 8) | raw[2]
    writer = DataWriter()
    writer.write_bytes(bytes(raw[4:]))

    msd = BluetoothLEManufacturerSpecificData()
    msd.company_id = company_id
    msd.data = writer.detach_buffer()

    adv = BluetoothLEAdvertisement()
    adv.manufacturer_data.append(msd)
    return BluetoothLEAdvertisementPublisher(adv)

# ── app state ─────────────────────────────────────────────────────────────────
running     = False
bg_thread   = None
publisher   = None
stop_event  = threading.Event()

def ad_loop(raw_fixed, status_var):
    global publisher
    while not stop_event.is_set():
        raw = random.choice(RANDOM_POOL) if raw_fixed is None else raw_fixed
        try:
            publisher = make_publisher(raw)
            publisher.start()
            stop_event.wait(2)
            publisher.stop()
        except Exception as e:
            status_var.set(f"Error: {e}")
            break

def start_advertising(raw, status_var):
    global running, bg_thread, stop_event
    running = True
    stop_event.clear()
    bg_thread = threading.Thread(target=ad_loop, args=(raw, status_var), daemon=True)
    bg_thread.start()

def stop_advertising():
    global running, publisher
    running = False
    stop_event.set()
    if publisher:
        try:
            publisher.stop()
        except Exception:
            pass

