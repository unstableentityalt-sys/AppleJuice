# ── Dependency bootstrap ──────────────────────────────────────────────────────

REQUIRED = [
    "winrt-runtime",
    "winrt-Windows.Devices.Bluetooth",
    "winrt-Windows.Storage.Streams",
]

def _winrt_available():
    try:
        importlib.import_module("winrt.windows.devices.bluetooth.advertisement")
        return True
    except Exception:
        return False

def _install_deps():
    """Show a splash window while pip installs winrt packages."""
    splash = tk.Tk()
    splash.title("AppleJuice")
    splash.geometry("340x140")
    splash.resizable(False, False)
    splash.configure(bg="#1a1a1a")
    splash.eval("tk::PlaceWindow . center")

    tk.Label(splash, text="🍎 AppleJuice", font=("Segoe UI", 16, "bold"),
             bg="#1a1a1a", fg="#f2f2f7").pack(pady=(22, 4))
    msg = tk.StringVar(value="Setting up for first run…")
    tk.Label(splash, textvariable=msg, font=("Segoe UI", 10),
             bg="#1a1a1a", fg="#8e8e93").pack()

    bar = ttk.Progressbar(splash, mode="indeterminate", length=280)
    bar.pack(pady=14)
    bar.start(12)

    done = threading.Event()
    error_holder = []

    def worker():
        try:
            for pkg in REQUIRED:
                subprocess.check_call(
                    [sys.executable, "-m", "pip", "install", "--quiet", pkg],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                )
        except Exception as e:
            error_holder.append(str(e))
        finally:
            done.set()

    threading.Thread(target=worker, daemon=True).start()

    def check():
        if done.is_set():
            bar.stop()
            splash.destroy()
        else:
            splash.after(100, check)

    splash.after(100, check)
    splash.mainloop()

    if error_holder:
        tk.messagebox.showerror(
            "Install failed",
            f"Could not install dependencies:\n{error_holder[0]}\n\n"
            "Try running as Administrator.",
        )
        sys.exit(1)

if not _winrt_available():
    _install_deps()

