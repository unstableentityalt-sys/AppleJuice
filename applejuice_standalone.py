RANDOM_POOL = [v for v in DEVICES.values() if v is not None]

# ── BLE advertising ───────────────────────────────────────────────────────────

def _make_publisher(raw):
    from winrt.windows.devices.bluetooth.advertisement import (
        BluetoothLEAdvertisement,
        BluetoothLEAdvertisementPublisher,
        BluetoothLEManufacturerSpecificData,
    )
    from winrt.windows.storage.streams import DataWriter

    company_id = (raw[3] << 8) | raw[2]
    writer = DataWriter()
    writer.write_bytes(bytes(raw[4:]))

    msd = BluetoothLEManufacturerSpecificData()
    msd.company_id = company_id
    msd.data = writer.detach_buffer()

    adv = BluetoothLEAdvertisement()
    adv.manufacturer_data.append(msd)
    return BluetoothLEAdvertisementPublisher(adv)

# ── App state ─────────────────────────────────────────────────────────────────

_running    = False
_publisher  = None
_stop_event = threading.Event()

def _ad_loop(raw_fixed, status_var, root):
    global _publisher
    while not _stop_event.is_set():
        raw = random.choice(RANDOM_POOL) if raw_fixed is None else raw_fixed
        try:
            _publisher = _make_publisher(raw)
            _publisher.start()
            _stop_event.wait(2)
            if _publisher:
                _publisher.stop()
        except Exception as e:
            root.after(0, lambda e=e: status_var.set(f"Error: {e}"))
            break

def _start(raw, status_var, root):
    global _running, _stop_event
    _running = True
    _stop_event.clear()
    threading.Thread(target=_ad_loop, args=(raw, status_var, root), daemon=True).start()

def _stop():
    global _running, _publisher
    _running = False
    _stop_event.set()
    if _publisher:
        try:
            _publisher.stop()
        except Exception:
            pass
        _publisher = None

