def build_advertisement(raw_bytes):
    """
    Build a BluetoothLEAdvertisement with manufacturer-specific data
    extracted from the raw HCI payload bytes.

    Raw format:
      [0]    = length (ignored here)
      [1]    = 0xff (AD type: manufacturer specific - ignored here)
      [2-3]  = company ID little-endian (0x4c, 0x00 = Apple)
      [4+]   = manufacturer payload
    """
    from winrt.windows.devices.bluetooth.advertisement import (
        BluetoothLEAdvertisement,
        BluetoothLEManufacturerSpecificData,
    )
    from winrt.windows.storage.streams import DataWriter

    company_id = (raw_bytes[3] << 8) | raw_bytes[2]   # little-endian: 0x004C
    payload = bytes(raw_bytes[4:])

    writer = DataWriter()
    writer.write_bytes(payload)
    data_buffer = writer.detach_buffer()

    msd = BluetoothLEManufacturerSpecificData()
    msd.company_id = company_id
    msd.data = data_buffer

    advert = BluetoothLEAdvertisement()
    advert.manufacturer_data.append(msd)
    return advert


def advertise(raw_bytes, duration_seconds=2):
    """Start advertising the given payload, wait, then stop."""
    from winrt.windows.devices.bluetooth.advertisement import (
        BluetoothLEAdvertisementPublisher,
        BluetoothLEAdvertisementPublisherStatus,
    )

    advert = build_advertisement(raw_bytes)
    publisher = BluetoothLEAdvertisementPublisher(advert)

    publisher.start()
    sleep(duration_seconds)
    publisher.stop()


def main():
    parser = argparse.ArgumentParser(
        description=help_desc,
        formatter_class=argparse.RawTextHelpFormatter,
    )
    parser.add_argument(
        "-i", "--interval",
        default=200, type=int,
        help="Seconds between advertisement changes in random mode (default 2)",
    )
    parser.add_argument(
        "-d", "--data",
        type=int,
        help="Select a specific message to send (e.g., -d 1)",
    )
    parser.add_argument(
        "-r", "--random",
        action="store_true",
        help="Randomly loop through advertising data",
    )
    args = parser.parse_args()

    if args.data is None and not args.random:
        print("Please select a message option using -d or use --random for random selection.\n")
        print("Available message options:")
        for option, description in bt_data_options.items():
            print(f"  {option:>2}: {description}")
        return

    if args.data and args.data not in bt_data_options:
        print(f"Invalid data option: {args.data}")
        print("Available data options:")
        for option, description in bt_data_options.items():
            print(f"  {option:>2}: {description}")
        return

    # Use interval as seconds to hold each advertisement (matches original semantics)
    hold_secs = max(1, args.interval)

    print("Advertising Started... Press Ctrl+C to Stop\n")

    try:
        if args.random:
            while True:
                selected_option = random.choice(list(bt_data_options.keys()))
                name = bt_data_options[selected_option]
                raw = hex_data[selected_option]
                print(f"  -> Sending: {name} (option {selected_option})")
                advertise(raw, duration_seconds=hold_secs)
        else:
            raw = hex_data[args.data]
            name = bt_data_options[args.data]
            print(f"  -> Sending: {name} (option {args.data})")
            while True:
                advertise(raw, duration_seconds=hold_secs)

    except KeyboardInterrupt:
        print("\nStopped.")


if __name__ == "__main__":
    main()
